"""
Real-Time State Manager for the Digital Twin Layer.

This module acts as the centralized in-memory datastore for the live railway state.
It manages active trains, active maintenance tasks, the generated plans,
and tracks versioning of plans (e.g., PLAN-V1, PLAN-V2).
"""

import time
from typing import Dict, List, Optional
from pydantic import BaseModel, Field

class RailwayEvent(BaseModel):
    event_id: str
    event_type: str # TRAIN_DELAYED, WEATHER_ALERT, NEW_DEFECT, etc.
    timestamp: str
    severity: str # LOW, MEDIUM, HIGH, CRITICAL
    source: str # LIVE (Weather), SIMULATED (Digital Twin)
    affected_assets: List[str] = []
    affected_trains: List[str] = []
    affected_blocks: List[str] = []
    description: str

class PlanVersion(BaseModel):
    plan_id: str
    version_num: int
    generated_timestamp: str
    trigger_event_id: Optional[str] = None
    blocks_scheduled: int
    objective_value: float
    # We store the snapshot of the schedule: list of dicts or block objects
    schedule_snapshot: List[Dict] = [] 

class RailwayState:
    def __init__(self):
        # Current active trains (Simulation Feed)
        self.active_trains: Dict[str, dict] = {}
        
        # Current live weather alerts (Live Feed)
        self.weather_alerts: List[dict] = []
        
        # Current high-risk assets
        self.critical_assets: Dict[str, dict] = {}
        
        # Event History
        self.event_feed: List[RailwayEvent] = []
        
        # Plan Versioning
        self.plan_history: List[PlanVersion] = []
        self.current_plan: Optional[PlanVersion] = None

    def add_event(self, event: RailwayEvent):
        """Append an event and keep the latest 100."""
        self.event_feed.insert(0, event)
        if len(self.event_feed) > 100:
            self.event_feed.pop()
            
    def update_train_delay(self, train_id: str, delay_minutes: int, location: str):
        """Update train state (Simulated Digital Twin)."""
        if train_id not in self.active_trains:
            self.active_trains[train_id] = {"train_id": train_id}
            
        self.active_trains[train_id]["delay"] = delay_minutes
        self.active_trains[train_id]["location"] = location
        self.active_trains[train_id]["last_updated"] = time.strftime("%Y-%m-%dT%H:%M:%S")

    def save_new_plan(self, blocks: List[dict], objective_val: float, trigger_event: Optional[str] = None):
        """Version the new plan generated by the CP-SAT optimizer."""
        new_version_num = 1 if not self.current_plan else self.current_plan.version_num + 1
        plan_id = f"PLAN-V{new_version_num}"
        
        plan = PlanVersion(
            plan_id=plan_id,
            version_num=new_version_num,
            generated_timestamp=time.strftime("%Y-%m-%dT%H:%M:%S"),
            trigger_event_id=trigger_event,
            blocks_scheduled=len(blocks),
            objective_value=objective_val,
            schedule_snapshot=blocks
        )
        
        self.plan_history.append(plan)
        self.current_plan = plan
        return plan_id

# Global singleton for the application
digital_twin_state = RailwayState()
